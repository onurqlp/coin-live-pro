import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('web/index.html','utf8');
const code=fs.readFileSync('web/app.js','utf8');
const local=fs.readFileSync('web/live-radar.js','utf8');
const pilot=fs.readFileSync('web/pilot-ui.js','utf8');
new Function(code);
new Function(local);
new Function(pilot);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size,'DOM IDs must be unique');
const used=[...(code+'\n'+local+'\n'+pilot).matchAll(/\$\('([^']+)'\)/g)].map(x=>x[1]);
assert.deepEqual([...new Set(used)].filter(x=>!ids.includes(x)),[],'All bound UI elements must exist');
for(const s of ['market','radar','history','reports','LONG','SHORT','CONFIRMED','WATCH','candleChart'])assert.ok((code+html).includes(s),s);
assert.ok(html.includes('data-window="7"')&&html.includes('data-window="14"'));
assert.ok(!html.includes('paperTrade'),'No paper trading desk');
for(const id of ['scanStatus','browserHistory'])assert.ok(ids.includes(id),'Missing live scanning progress UI: '+id);
assert.ok(html.includes('live-radar.js?'),'Independent live scanner must load');
assert.ok(local.includes('15*60000')&&local.includes("'15m','1H','4H'"),'Browser scanner must use 15-minute scans with all 3 timeframes');
assert.ok(local.includes('clpro.local_events_v1'),'Device-only spark history must be retained');
assert.ok(code.includes("mode:'SERVER'")&&code.includes("mode:'STALE'")&&!code.includes("mode:'BROWSER'"),'Only central server radar may issue authoritative signals');
for(const id of ['chartTf','mtfPanel','mtfStatus','mtfCandidates','macroRegime','paperPanel','paperKpis','paperRows','systemPanel','systemKpis','systemDetail'])assert.ok(ids.includes(id),'Missing pilot panel: '+id);
assert.ok(html.includes('pilot-ui.js?'),'Central pilot report UI must be loaded');
assert.ok(code.includes('Pilot: bildirim kapalı'),'Pilot must not enable browser notifications');
assert.ok(!local.includes('setInterval(()=>{scan()'),'Browser standalone scan must not run unattended or become canonical');
console.log('PASS: responsive dashboard contract, 7/14 history, chart selector, dual-side radar');